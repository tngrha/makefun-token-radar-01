// The token radar's model: one snapshot of the protocol universe in, one ranked board out.
//
// The board ranks pre-token DeFi protocols by the value a token would carry if it launched at the
// multiple its own category's launched protocols trade at. Nothing here is a hardcoded list of names:
// every number comes from the snapshot's own figures.
//
//   multiple     = the median market-cap / TVL of the snapshot's launched protocols in the same
//                  category (at least 3 of them), else the median over all launched protocols.
//   implied      = tvl_usd x multiple x growth x maturity
//   growth       = 1 + clamp(change_7d, -60, 120) / 100 x 0.5   (change_7d unknown: 1)
//   maturity     = 0.6 + min(age_days, 1095) / 1095 x 0.4       (listed_at unknown: 365 days)
//
// Eligibility is the house watchlist's own rule, applied to the whole snapshot instead of only the
// $50M floor: pre-token (no market cap, no CoinGecko id, no symbol), not an exchange, not a bridge
// or a liquid-staking product, no version marker in the name, no whole word wrapped / staked /
// staking, and not starting with an exchange's name. A wrapped or staked product of a token that
// already trades (WBTC, Binance staked ETH, USDT0) is not a protocol still waiting on a launch, so
// it never ranks, however large its TVL. The launched protocols are not ranked at all: they are the
// comparables the multiples are read from, and the dashboard shows them apart, as the market's own
// values.
//
// Every farm plan is derived from the protocol's own record (category, chains, TVL, age), never from
// a hand-written list of names: the same function plans every row.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

/** The model's constants, as the dashboard states them. */
export interface ModelConstants {
  growth_weight: number;
  growth_floor: number;
  growth_cap: number;
  maturity_floor: number;
  maturity_range: number;
  maturity_days: number;
  unknown_age_days: number;
  min_category_samples: number;
}

export const MODEL: ModelConstants = {
  growth_weight: 0.5,
  growth_floor: -60,
  growth_cap: 120,
  maturity_floor: 0.6,
  maturity_range: 0.4,
  maturity_days: 1095,
  unknown_age_days: 365,
  min_category_samples: 3,
};

/** The model's version label: the dashboard names it. */
export const MODEL_VERSION = 'radar-2';

